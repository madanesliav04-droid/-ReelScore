"""App launch check only. Never claims a private-rush export succeeded."""
import json, subprocess, sys, os, time, shutil
from pathlib import Path

def run(*args):
    return subprocess.check_output(args, text=True)

devices = json.loads(run('xcrun', 'simctl', 'list', 'devices', 'available', '--json'))['devices']
phones = [d for runtime, ds in devices.items() if 'iOS' in runtime
          for d in ds if 'iPhone' in d['name'] and d.get('isAvailable')]
if not phones:
    raise SystemExit('No available iPhone simulator. No runtime download requested.')
device = phones[0]
udid = device['udid']
booted_here = device['state'] != 'Booted'
try:
    if booted_here:
        run('xcrun', 'simctl', 'boot', udid)
    run('xcrun', 'simctl', 'bootstatus', udid, '-b')
    # arm64 Simulator executables require a local ad-hoc signature; no Apple account.
    run('codesign', '--force', '--deep', '--sign', '-', sys.argv[1])
    run('xcrun', 'simctl', 'install', udid, sys.argv[1])
    run('xcrun', 'simctl', 'launch', udid, 'local.socialplus.v28lab', '--synthetic-ci')
    container = Path(run('xcrun', 'simctl', 'get_app_container', udid, 'local.socialplus.v28lab', 'data').strip())
    result = container / 'Documents/ci-result.json'
    deadline = time.monotonic() + 420
    while not result.exists():
        if time.monotonic() > deadline:
            raise RuntimeError('Timed out after 420s waiting for iOS export report')
        time.sleep(2)
    data = json.loads(result.read_text())
    print(json.dumps(data))
    if not data.get('success'):
        raise RuntimeError('iOS renderer: ' + data.get('description', str(data)))
    out = Path(os.environ['RUNNER_TEMP']) / 'v28-proof'
    out.mkdir(exist_ok=True)
    shutil.copy2(container / 'Documents/SocialPlus-synthetic-iOS.mp4', out)
    shutil.copy2(result, out)
    report = 'Synthetic MP4 generated by iOS simulator WKWebView/Core Image/AVFoundation. Fidelity to approved rush NOT tested.' 
    print(report)
    if os.getenv('GITHUB_STEP_SUMMARY'):
        with open(os.environ['GITHUB_STEP_SUMMARY'], 'a') as f:
            f.write(report + '\n')
except Exception:
    reports = sorted((Path.home() / 'Library/Logs/DiagnosticReports').glob('SocialPlusV28Lab*'), key=lambda p: p.stat().st_mtime)
    for report in reports[-2:]:
        print(report.read_text(errors='replace')[-12000:])
    raise
finally:
    if booted_here:
        subprocess.run(['xcrun', 'simctl', 'shutdown', udid], check=False)
